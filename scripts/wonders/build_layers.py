#!/usr/bin/env python3
"""Build per-color reveal layers for every wonder in wonders.json.

For each wonder, reads  assets/wonders/<id>/final.png  (hand-made master:
1600x1200, exactly 10 colors) and writes
    assets/wonders/<id>/layer_0.webp ... layer_9.webp
one transparent 800x600 lossless WebP per color. Layers never overlap (every
pixel has exactly one color), so they can be stacked in any order, which is what
lets the app unlock colors in a random order.

Also regenerates app/lib/wondersData.ts (Metro needs literal require() calls).

Usage:  python3 -I scripts/wonders/build_layers.py
Needs:  Pillow, numpy
"""
import json
import pathlib
import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets" / "wonders"
OUT_TS = ROOT / "app" / "lib" / "wondersData.ts"
LAYER_SIZE = (800, 600)   # native painting resolution; the master is an exact 2x upscale
N_COLORS = 10


def build(wonder):
    wid = wonder["id"]
    src = ASSETS / wid / "final.png"
    master = Image.open(src).convert("RGB")
    assert master.size == (1600, 1200), f"{wid}: master must be 1600x1200, got {master.size}"
    colors = sorted(c for _, c in master.getcolors(1 << 20))
    assert len(colors) == N_COLORS, f"{wid}: master must have exactly {N_COLORS} colors, has {len(colors)}"

    small = master.resize(LAYER_SIZE, Image.NEAREST)
    # the downscale must be lossless, otherwise the 800x600 layers would not match the master
    assert small.resize(master.size, Image.NEAREST).tobytes() == master.tobytes(), \
        f"{wid}: master is not an exact 2x upscale of an 800x600 image"

    a = np.array(small)
    for i, c in enumerate(colors):
        mask = (a == np.array(c)).all(-1)
        rgba = np.zeros(a.shape[:2] + (4,), np.uint8)
        rgba[mask] = (*c, 255)
        Image.fromarray(rgba, "RGBA").save(
            ASSETS / wid / f"layer_{i}.webp", "WEBP", lossless=True, quality=100, method=6)
    return ["#%02X%02X%02X" % c for c in colors]


def main():
    wonders = json.loads((pathlib.Path(__file__).parent / "wonders.json").read_text())
    entries = []
    for w in wonders:
        palette = build(w)
        layers = ",\n".join(
            f"      require('../../assets/wonders/{w['id']}/layer_{i}.webp')" for i in range(N_COLORS))
        entries.append(
            "  {\n"
            f"    id: '{w['id']}',\n"
            f"    name: {json.dumps(w['name'])},\n"
            f"    cca2: '{w['cca2']}',\n"
            f"    palette: {json.dumps(palette)},\n"
            f"    layers: [\n{layers},\n    ],\n"
            "  }")
        print(f"{w['id']}: wrote {N_COLORS} layers")
    OUT_TS.write_text(
        "// AUTO-GENERATED by scripts/wonders/build_layers.py. Do not edit by hand.\n"
        "import { ImageSourcePropType } from 'react-native';\n\n"
        "export interface Wonder {\n"
        "  id: string;\n"
        "  name: string;\n"
        "  /** Country the wonder belongs to (ISO 3166-1 alpha-2). */\n"
        "  cca2: string;\n"
        "  /** Hex color of each layer, same index as `layers`. */\n"
        "  palette: string[];\n"
        "  /** One transparent 800x600 image per color. Layers never overlap. */\n"
        "  layers: ImageSourcePropType[];\n"
        "}\n\n"
        "export const WONDER_COLOR_COUNT = 10;\n\n"
        "export const WONDERS: Wonder[] = [\n" + ",\n".join(entries) + ",\n];\n\n"
        "export function getWonder(id: string): Wonder | undefined {\n"
        "  return WONDERS.find((w) => w.id === id);\n"
        "}\n")
    print(f"wrote {OUT_TS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
