-- Daily chest tiers: seeded from the LIVE daily_chest_tiers table so nothing changes at launch.
INSERT INTO public.game_config(key, value, category, description, min_value, max_value)
SELECT 'chest.t'||tier||'.'||f.field, f.val, 'Daily chest', name||' chest: '||f.label, f.mn, f.mx
FROM public.daily_chest_tiers t
CROSS JOIN LATERAL (VALUES
  ('gold', t.gold::numeric, 'gold reward', 0, 1000000),
  ('tickets', t.tickets::numeric, 'ticket reward', 0, 1000),
  ('duration', t.duration::numeric, 'potion duration (quizzes, 2-5)', 2, 5),
  ('odds_gold', t.odds[1]::numeric, 'chance % gold', 0, 100),
  ('odds_tickets', t.odds[2]::numeric, 'chance % tickets', 0, 100),
  ('odds_xp_potion', t.odds[3]::numeric, 'chance % XP potion', 0, 100),
  ('odds_gold_potion', t.odds[4]::numeric, 'chance % gold potion', 0, 100),
  ('odds_avatar', t.odds[5]::numeric, 'chance % avatar', 0, 100)
) AS f(field, val, label, mn, mx)
ON CONFLICT (key) DO NOTHING;

-- Dashboard edits to chest.tN.* flow into daily_chest_tiers (the table claim_daily_chest reads).
-- Odds are only applied once the five odds add up to 100 (the table's own CHECK), so edit them together.
CREATE OR REPLACE FUNCTION public.game_config_sync_chest() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE t integer := substring(NEW.key from '^chest\.t(\d)\.')::integer;
        o numeric[];
BEGIN
  IF t IS NULL THEN RETURN NEW; END IF;
  o := ARRAY[cfg('chest.t'||t||'.odds_gold', 0), cfg('chest.t'||t||'.odds_tickets', 0), cfg('chest.t'||t||'.odds_xp_potion', 0),
             cfg('chest.t'||t||'.odds_gold_potion', 0), cfg('chest.t'||t||'.odds_avatar', 0)];
  UPDATE public.daily_chest_tiers d SET
    gold = cfg('chest.t'||t||'.gold', d.gold)::integer,
    tickets = cfg('chest.t'||t||'.tickets', d.tickets)::integer,
    duration = cfg('chest.t'||t||'.duration', d.duration)::integer,
    odds = CASE WHEN o[1]+o[2]+o[3]+o[4]+o[5] = 100 THEN ARRAY[o[1],o[2],o[3],o[4],o[5]]::integer[] ELSE d.odds END
  WHERE d.tier = t;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS game_config_sync_chest ON public.game_config;
CREATE TRIGGER game_config_sync_chest AFTER INSERT OR UPDATE ON public.game_config
  FOR EACH ROW WHEN (NEW.key LIKE 'chest.t%') EXECUTE FUNCTION public.game_config_sync_chest();
